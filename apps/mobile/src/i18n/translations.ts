type TranslationDictionary = typeof translations.fa;
export type TranslationKey = keyof TranslationDictionary;
type TranslationParams = Record<string, string | number>;

export function resolveLanguage(input: string | null | undefined): AppLanguage | null {
  if (input === "fa" || input === "en") {
    return input;
  }

  return null;
}

export function getDefaultLanguage(): AppLanguage {
  const locale = Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase();

  return locale.startsWith("fa") ? "fa" : "en";
}

export function translate(language: AppLanguage, key: TranslationKey, params?: TranslationParams) {
  const template = translations[language][key] ?? translations[fallbackLanguage][key];

  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, token: string) => {
    const value = params[token];
    return value === undefined ? `{${token}}` : `${value}`;
  });
}
