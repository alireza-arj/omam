import { _electron, expect } from "@playwright/test";
import { createRequire } from "node:module";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { resolve, join } from "node:path";
import type { DesktopApi } from "@omam/contracts";
import type { WebContents, WebPreferences } from "electron";
import { createTranslator } from "@omam/i18n";

const root = resolve(process.cwd(), "../..");
const packaged = process.env.OMAM_DESKTOP_EXECUTABLE;
const output = resolve(root, `output/playwright/desktop${packaged ? "-packaged" : ""}`);
const data = await mkdtemp(join(tmpdir(), "omam-desktop-verify-"));
await mkdir(output, { recursive: true });
const app = await _electron.launch({ timeout: 30_000, executablePath: packaged ?? createRequire(import.meta.url)("electron") as string, args: packaged ? [] : [resolve(root, "apps/desktop")], env: { ...process.env, TZ: "Europe/Berlin", OMAM_DESKTOP_DATA_DIR: data, OMAM_DESKTOP_SHOW: "1" } });
const errors: string[] = [];
try {
  const page = await app.firstWindow();
  const shell = await app.evaluate(({ app, BrowserWindow }) => {
    const windows = BrowserWindow.getAllWindows();
    const contents = windows[0]?.webContents as WebContents & { getLastWebPreferences(): WebPreferences };
    const preferences = contents.getLastWebPreferences();
    return { windows: windows.length, dock: app.dock?.isVisible(), sandbox: preferences.sandbox, contextIsolation: preferences.contextIsolation };
  });
  expect(shell).toEqual({ windows: 1, dock: false, sandbox: true, contextIsolation: true });
  page.on("pageerror", (error) => errors.push(error.message));
  page.on("console", (message) => { if (message.type() === "error") console.error(message.text()); });
  await page.waitForSelector(".desktop-panel", { timeout: 30_000 });
  await page.screenshot({ path: join(output, "login.png") });
  await page.evaluate(async () => {
    const bridge = (globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop;
    const now = new Date().toISOString();
    await bridge.database({ operation: "run", sql: "INSERT INTO User (id, username, nickname, passwordHash, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?)", params: ["test-user", "sara", "Sara", "test-fixture", now, now] });
    await bridge.database({ operation: "run", sql: "INSERT INTO AppSettings (id, userId, hourlyRate, currency, monthlyGoalHours, calendar, language, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", params: ["settings", "test-user", 0, "IRR", 160, "JALALI", "en", now, now] });
    await bridge.database({ operation: "run", sql: "INSERT INTO WorkSession (id, userId, startAt, endAt, durationMinutes, category, note, status, source, deviceName, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", params: ["finished", "test-user", new Date(Date.now() - 7 * 3600_000).toISOString(), new Date(Date.now() - 4 * 3600_000).toISOString(), 180, "REMOTE", "Design system", "COMPLETED", "TIMER", "Mac", now, now] });
    await bridge.database({ operation: "run", sql: "INSERT INTO WorkSession (id, userId, startAt, category, status, source, deviceName, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)", params: ["running", "test-user", new Date(Date.now() - 83 * 60_000).toISOString(), "REMOTE", "OPEN", "TIMER", "iPhone", now, now] });
    await bridge.storage({ operation: "set", key: "@omam:loggedIn", value: JSON.stringify({ userId: "test-user" }) });
    await bridge.storage({ operation: "set", key: "taraz.theme-mode", value: "light" });
  });
  await page.reload();
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  expect(await page.getByRole("button", { name: "Timer", exact: true }).evaluate((element) => getComputedStyle(element).backgroundColor)).not.toBe("rgba(0, 0, 0, 0)");
  await page.keyboard.press("Escape");
  await expect.poll(() => app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0]?.isVisible())).toBe(false);
  await app.evaluate(({ BrowserWindow }) => { const panel = BrowserWindow.getAllWindows()[0]; panel?.show(); panel?.focus(); });
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  await page.screenshot({ path: join(output, "timer-light.png") });
  await page.getByRole("button", { name: "Stop", exact: true }).click();
  await expect(page.getByRole("button", { name: "Start", exact: true })).toBeVisible();
  const stopped = await page.evaluate(async () => ((globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop.database({ operation: "first", sql: "SELECT status, durationMinutes FROM WorkSession WHERE id = 'running'" })));
  expect(stopped).toMatchObject({ status: "COMPLETED", durationMinutes: 83 });
  await page.getByRole("button", { name: "Start", exact: true }).click();
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "History", exact: true }).click();
  await expect(page.getByRole("button", { name: "Add session", exact: true })).toBeVisible();
  await page.screenshot({ path: join(output, "history-light.png") });
  await page.getByRole("button", { name: "Add session", exact: true }).click();
  await expect(page.getByRole("heading", { name: "New session", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Report", exact: true }).click();
  await expect(page.getByText("Report", { exact: true }).last()).toBeVisible();
  await page.screenshot({ path: join(output, "report-light.png") });
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await expect(page.getByRole("button", { name: "Check for updates", exact: true })).toBeVisible();
  const saveProfile = page.getByRole("button", { name: "Save profile", exact: true });
  await expect(saveProfile).toBeVisible();
  expect(await saveProfile.evaluate((element) => getComputedStyle(element).backgroundColor)).not.toBe("rgba(0, 0, 0, 0)");
  await page.screenshot({ path: join(output, "settings-light.png") });
  await page.evaluate(async () => { await (globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop.storage({ operation: "set", key: "taraz.theme-mode", value: "dark" }); });
  await page.reload();
  await expect(page.getByRole("button", { name: "Stop", exact: true })).toBeVisible();
  await page.screenshot({ path: join(output, "timer-dark.png") });
  const chosen = await page.evaluate(async () => {
    const bridge = (globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop;
    const session = await bridge.database({ operation: "first", sql: "SELECT id, startAt FROM WorkSession WHERE endAt IS NULL AND deletedAt IS NULL" }) as { id: string; startAt: string };
    const now = new Date().toISOString();
    await bridge.database({ operation: "run", sql: "INSERT INTO WorkSession (id, userId, startAt, category, status, source, deviceId, deviceName, dirty, createdAt, updatedAt) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)", params: ["competing-phone", "test-user", new Date(Date.now() - 120_000).toISOString(), "REMOTE", "OPEN", "TIMER", "phone-device", "iPhone", 0, now, now] });
    await bridge.database({ operation: "run", sql: "UPDATE WorkSession SET syncError = 'SESSION_CONFLICT' WHERE id = ?", params: [session.id] });
    return session;
  });
  await page.reload();
  await expect(page.getByRole("heading", { name: "Choose your session", exact: true })).toBeVisible();
  await expect(page.locator(".dt-choice")).toHaveCount(2);
  await page.screenshot({ path: join(output, "conflict-dark.png") });
  await page.locator(".dt-choice").filter({ hasText: "Mac" }).click();
  await expect(page.locator(".dt-conflict")).toHaveCount(0);
  const resolution = await page.evaluate(async () => {
    const bridge = (globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop;
    return { live: await bridge.database({ operation: "all", sql: "SELECT id, startAt FROM WorkSession WHERE endAt IS NULL AND deletedAt IS NULL" }), loser: await bridge.database({ operation: "first", sql: "SELECT deletedAt, dirty FROM WorkSession WHERE id = 'competing-phone'" }) };
  });
  expect(resolution.live).toEqual([chosen]);
  expect(resolution.loser).toMatchObject({ dirty: 1, deletedAt: expect.any(String) });
  await page.evaluate(async () => {
    const bridge = (globalThis as typeof globalThis & { omamDesktop: DesktopApi }).omamDesktop;
    await bridge.database({ operation: "run", sql: "UPDATE AppSettings SET language = 'fa' WHERE userId = 'test-user'" });
  });
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.reload();
  await expect(page.locator(".desktop-panel")).toHaveAttribute("dir", "rtl");
  await expect(page.getByRole("button", { name: createTranslator("fa")("today.stop"), exact: true })).toBeVisible();
  await page.screenshot({ path: join(output, "timer-fa-dark.png") });
  expect(await page.locator(".dt-time").evaluate((element) => getComputedStyle(element).direction)).toBe("ltr");
  expect(await page.locator(".desktop-panel").evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect(errors).toEqual([]);
  console.log(`Electron verification passed. Screenshots: ${output}`);
} finally {
  await app.close();
  await rm(data, { recursive: true, force: true });
}
